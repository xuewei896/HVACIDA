        /// <summary>全部章节。</summary>
        public static IList<RevitGuideSection> All => Sections;

        /// <summary>分组名(界面筛选用)。</summary>
        public static IList<string> Groups()
        {
            var groups = new List<string>();
            foreach (var section in Sections)
            {
                if (!groups.Contains(section.Group)) groups.Add(section.Group);
            }
            return groups;
        }

        /// <summary>按分组取章节。</summary>
        public static IList<RevitGuideSection> ByGroup(string group)
        {
            var result = new List<RevitGuideSection>();
            foreach (var section in Sections)
            {
                if (string.Equals(section.Group, group, StringComparison.Ordinal)) result.Add(section);
            }
            return result;
        }

        /// <summary>按标题 / 关键词 / 步骤检索。</summary>
        public static IList<RevitGuideSection> Search(string query)
        {
            var matches = new List<RevitGuideSection>();
            if (string.IsNullOrEmpty(query)) return matches;

            string text = query.Trim();
            var tokens = KnowledgeBase.TokenizeForSearch(text);
            foreach (var section in Sections)
            {
                if (Hit(section, text)) { matches.Insert(0, section); continue; }
                foreach (var token in tokens)
                {
                    if (string.IsNullOrEmpty(token)) continue;
                    if (Hit(section, token)) { matches.Add(section); break; }
                }
            }
            return matches;
        }

        private static bool Hit(RevitGuideSection section, string token)
        {
            if (Contains(section.Title, token) || Contains(section.Summary, token) || Contains(section.Group, token))
                return true;
            foreach (var keyword in section.Keywords)
            {
                if (Contains(keyword, token) || Contains(token, keyword)) return true;
            }
            foreach (var step in section.Steps)
            {
                if (Contains(step, token)) return true;
            }
            return false;
        }

        private static bool Contains(string text, string token)
        {
            return !string.IsNullOrEmpty(text) && !string.IsNullOrEmpty(token) &&
                   text.IndexOf(token, StringComparison.OrdinalIgnoreCase) >= 0;
        }

        private static RevitGuideSection Section(string id, string group, string title, string summary,
            string note, string[] steps, params string[] keywords)
        {
            var section = new RevitGuideSection
            {
                Id = id,
                Group = group,
                Title = title,
                Summary = summary,
                Note = note
            };
            section.Steps.AddRange(steps);
            section.Keywords.AddRange(keywords);
            return section;
        }

